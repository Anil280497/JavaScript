
let Name = "John Doe";

let age = 25;
let pi = 3.14;    // its not a boolean literal, its a number literal

let isStudent = true;
let isEmployed = false;

let I_have_car = null; // Null literal, it represents the intentional absence of any object value.
let car;               // explaination: car is undefined because it has not been assigned a value yet.

let Big_IntValue = 1234567890123456789012345678901234567890n; // BigInt literal, it represents a large integer value.   
 
console.log(typeof Name);          // string
console.log(typeof age);           // number       
console.log(typeof pi);            // number
console.log(typeof isStudent);     // boolean
console.log(typeof isEmployed);    // boolean
console.log(typeof I_have_car);    // object
console.log(typeof car);           // undefined  
console.log(typeof Big_IntValue);  // bigint  

